// deploy.mjs — build the static export, check it, and put it on Cloudflare Pages.
//
//   node tools/deploy.mjs                      a preview: https://preview.prism-compiler.pages.dev
//   node tools/deploy.mjs --branch=<name>      a preview under another name: https://<name>.prism-compiler.pages.dev
//   node tools/deploy.mjs --production         https://prism-compiler.pages.dev (a clean tree only)
//   ... --skip-build                           send site/ as it is
//   ... --sources=release[:tag]                passed to site.mjs (the release-day export)
//   ... --open                                 a preview with no password
//
// Direct upload, never Cloudflare's Git build: site/ is made of files the repository does not hold
// (the bundle cache, game data, source archives). wrangler must be logged in (npx wrangler login).
//
// A PREVIEW IS LOCKED. Its deployment carries a Pages Function that asks for a password (HTTP basic
// auth, any user name) before serving anything; production carries none, and stays plain static
// files. The password is read from $PRISM_PREVIEW_PASSWORD or ~/.config/prism/preview-password and
// never enters the deployment: the Function holds its SHA-256 only. The Function also sets the
// COOP/COEP headers itself, since _headers is not promised to apply to what a Function returns.
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const PROJECT = 'prism-compiler';
const WRANGLER = 'wrangler@4.151.1';
const SITE = join(ROOT, 'site');
const arg = (n) => process.argv.find((a) => a.startsWith(`--${n}=`))?.slice(n.length + 3);
const flag = (n) => process.argv.includes(`--${n}`);
const production = flag('production');
const branch = production ? 'main' : (arg('branch') ?? 'preview');
const die = (msg) => { console.error(`deploy: ${msg}`); process.exit(1); };
const run = (cmd, args, opts = {}) => {
  console.log(`\n$ ${[cmd, ...args].join(' ')}`);
  const r = spawnSync(cmd, args, { stdio: 'inherit', cwd: ROOT, ...opts });
  if (r.status !== 0) die(`${cmd} ${args[0] ?? ''} failed`);
};
const git = (...a) => spawnSync('git', ['-C', ROOT, ...a], { encoding: 'utf8' }).stdout.trim();

const dirty = git('status', '--porcelain') !== '';
if (production && dirty) die('production is deployed from a clean tree: commit first (git status shows changes)');

let hash = null;
if (!production && !flag('open')) {
  const file = join(homedir(), '.config/prism/preview-password');
  const pass = process.env.PRISM_PREVIEW_PASSWORD ?? (existsSync(file) ? readFileSync(file, 'utf8').split('\n')[0] : '');
  if (!pass) die(`a preview needs a password: put it in ${file} (first line) or $PRISM_PREVIEW_PASSWORD, or pass --open`);
  hash = createHash('sha256').update(pass).digest('hex');
}

if (!flag('skip-build')) {
  const sources = arg('sources');
  run('node', ['tools/site.mjs', ...(sources ? [`--sources=${sources}`] : [])]);
}
run('node', ['tools/site-check.mjs', SITE]);

// wrangler compiles ./functions from its working directory: a preview runs from a folder holding the
// lock, production from the repository, which has no functions/.
let cwd = ROOT;
if (hash) {
  cwd = join(ROOT, 'dist/deploy');
  rmSync(cwd, { recursive: true, force: true });
  mkdirSync(join(cwd, 'functions'), { recursive: true });
  writeFileSync(join(cwd, 'functions/_middleware.js'), `// Generated by tools/deploy.mjs: a preview asks for its password before serving anything.
const HASH = '${hash}';
const ISOLATION = {
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Embedder-Policy': 'require-corp',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'X-Robots-Tag': 'noindex',
};
const hex = (buf) => [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('');
export async function onRequest({ request, next }) {
  const auth = request.headers.get('Authorization') ?? '';
  let pass = null;
  if (auth.startsWith('Basic ')) {
    try { const s = new TextDecoder().decode(Uint8Array.from(atob(auth.slice(6)), (c) => c.charCodeAt(0))); pass = s.slice(s.indexOf(':') + 1); } catch {}
  }
  if (pass === null || hex(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(pass))) !== HASH) {
    return new Response('PRISM preview: sign in with the preview password (any user name).\\n', {
      status: 401, headers: { 'WWW-Authenticate': 'Basic realm="PRISM preview", charset="UTF-8"', 'Cache-Control': 'no-store' },
    });
  }
  const res = await next();
  const out = new Response(res.body, res);
  for (const [k, v] of Object.entries(ISOLATION)) out.headers.set(k, v);
  return out;
}
`);
}

const sha = git('rev-parse', 'HEAD'), subject = git('log', '-1', '--format=%s');
run('npx', ['--yes', WRANGLER, 'pages', 'deploy', SITE, `--project-name=${PROJECT}`, `--branch=${branch}`,
  `--commit-hash=${sha}`, `--commit-message=${subject}`, `--commit-dirty=${dirty}`], { cwd });

// What a visitor gets: production open and isolated; a preview closed without its password.
const url = production ? `https://${PROJECT}.pages.dev/` : `https://${branch}.${PROJECT}.pages.dev/`;
let res = null;
for (let i = 0; i < 10; i++) {
  res = await fetch(url, { redirect: 'manual' }).catch(() => null);
  if (res && (production ? res.status === 200 : res.status === 401)) break;
  await new Promise((r) => setTimeout(r, 3000));
}
const coep = res?.headers.get('cross-origin-embedder-policy');
if (production) {
  if (res?.status !== 200 || coep !== 'require-corp') die(`${url} answers ${res?.status}, COEP ${coep}: check it before announcing anything`);
  console.log(`\n${url} is live, cross-origin isolated.`);
} else if (hash) {
  if (res?.status !== 401) die(`${url} answers ${res?.status} without a password: the lock is not in place`);
  console.log(`\n${url} is up and asks for its password.`);
} else {
  console.log(`\n${url} is up, open to anyone with the link (--open).`);
}
