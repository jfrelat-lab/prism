// gen-glut-h.mjs — PRISM's <GL/glut.h>, from GLUT 3.7's own (corpus/glut-3.7-dist), written into
// src/env/headers-gl.js between its GENERATED markers.
//
// Every constant GLUT 3.7 defines, and every one of its 114 entry points, declared as GLUT 3.7 declares
// them, so that a GLUT program finds what it would on a real system -- and the reference build of the
// GL gates (tools/oracle.mjs's oracleGlut) compiles against this very text, so the two sides cannot
// disagree on a value. Two choices: the fonts are GLUT's WIN32 identifiers, small integers cast to a
// pointer (GLUT_BITMAP_8_BY_13 is ((void*)3)) rather than the addresses of extern data its Unix header
// uses -- the integer is a constant a static initialiser may hold, as programs write
// `static void *font = GLUT_BITMAP_8_BY_13;` -- and GLUT_API_VERSION is 4, every function being declared.
//
//   node tools/gen-glut-h.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const src = readFileSync(join(ROOT, 'corpus/glut-3.7-dist/glut-3.7/include/GL/glut.h'), 'latin1');

const defines = new Map();
for (const m of src.matchAll(/^#define\s+(GLUT_\w+)[ \t]+([^\n]*?)\s*(?:\/\*.*)?$/gm)) {
  const [, name, value] = m;
  if (!value || value.startsWith('(&') || name === 'GLUT_APIENTRY_DEFINED' || name === 'GLUT_XLIB_IMPLEMENTATION') continue;
  if (!defines.has(name)) defines.set(name, name === 'GLUT_API_VERSION' ? '4' : value);
}

// The prototypes: `extern <ret> APIENTRY glutX(<params>);`, parameters with function-pointer types.
const protos = new Map();
const re = /extern\s+([\w\s*]+?)\s*APIENTRY\s+(glut\w+)\s*\(/g;
for (let m; (m = re.exec(src));) {
  let i = re.lastIndex, depth = 1;
  while (depth) { const c = src[i++]; if (c === '(') depth++; else if (c === ')') depth--; }
  const params = src.slice(re.lastIndex, i - 1).replace(/\s+/g, ' ').replace(/GLUTCALLBACK\s*/g, '').trim();
  if (!protos.has(m[2])) protos.set(m[2], `${m[1].replace(/\s+/g, ' ')} ${m[2]}(${params});`);
}
if (protos.size !== 114) throw new Error(`expected GLUT 3.7's 114 entry points, found ${protos.size}`);

const body = [
  `/* GENERATED by tools/gen-glut-h.mjs from GLUT 3.7's include/GL/glut.h (Copyright (c) Mark J. Kilgard,`,
  `   1994-1998; freely distributable without licensing fees). Do not edit between the markers. */`,
  ...[...defines].map(([n, v]) => `#define ${n} ${v}`),
  ...protos.values(),
].join('\n');
const H = join(ROOT, 'src/env/headers-gl.js');
const text = readFileSync(H, 'utf8');
const a = '/* GLUT-GENERATED-BEGIN */\n', b = '/* GLUT-GENERATED-END */\n';
const i = text.indexOf(a), j = text.indexOf(b);
if (i < 0 || j < 0) throw new Error('headers-gl.js has no GLUT-GENERATED markers');
writeFileSync(H, text.slice(0, i + a.length) + body.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '\n' + text.slice(j));
console.log(`${defines.size} constants, ${protos.size} entry points -> src/env/headers-gl.js`);
