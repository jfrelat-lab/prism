// gen-glu-c.mjs — GLU 9.0.2's tessellator, libtess, as C: from corpus/glu-9.0.2, written to
// src/env/glu-c.js as one unit per libtess source file.
//
// gluNewTess and the rest are GLU 9's own C compiled beside the program, as GLUT's shapes are GLUT's
// (gen-glut-c.mjs): the reference build links Debian's libGLU, which is GLU 9.0.2 too. The glu
// environment adds these units only to a program that calls the tessellator and does not compile
// libtess itself (registry.js, `when`). What is changed, and only that: each unit's own headers are
// written into it, and gluos.h -- the platform header, which on anything but Windows and VMS defines
// GLAPIENTRY and WINGDIAPI as nothing -- becomes those two definitions.
//
//   node tools/gen-glu-c.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const LIB = join(ROOT, 'corpus/glu-9.0.2/src/libtess');
const read = (f) => readFileSync(join(LIB, f), 'latin1');
const GLUOS = '#define GLAPIENTRY\n#define WINGDIAPI';
// A quoted include of libtess's own, written in place, its include guards keeping a header that
// comes twice to once; string.h, quoted in one unit, is the C library's.
const inline = (src, f) => src.replace(/^#include "([\w.-]+)"[^\n]*$/gm, (_, h) => (h === 'gluos.h' ? GLUOS : !existsSync(join(LIB, h)) ? `#include <${h}>` : `/* ---- ${h} ---- */\n${inline(read(h), h)}`));
const FILES = ['dict.c', 'geom.c', 'memalloc.c', 'mesh.c', 'normal.c', 'priorityq.c', 'render.c', 'sweep.c', 'tess.c', 'tessmono.c'];
const units = FILES.map((f) => ({ file: `glu-c-${f}`, source: `/* ---- GLU 9.0.2 src/libtess/${f} ---- */\n${inline(read(f), f)}` }));
const names = [...new Set(units.flatMap((u) => [...u.source.matchAll(/^(glu\w+)\s*\(/gm)].map((m) => m[1])))];
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
writeFileSync(join(ROOT, 'src/env/glu-c.js'), `// GENERATED by tools/gen-glu-c.mjs from GLU 9.0.2's libtess (Copyright (C) 1991-2000 Silicon Graphics,
// Inc., SGI Free Software License B 2.0, its notice kept in the text; see THIRD-PARTY.md). Do not edit.
/** GLU 9's tessellator, as C compiled beside the program: one unit per libtess source file. */
export const GLU_C = [
${units.map((u) => `  { file: '${u.file}', source: \`${esc(u.source)}\` },`).join('\n')}
];
/** The entry points GLU_C defines, which are therefore not builtins. */
export const GLU_C_NAMES = ${JSON.stringify(names)};
`);
console.log(`${names.length} entry points in ${units.length} units -> src/env/glu-c.js`);
