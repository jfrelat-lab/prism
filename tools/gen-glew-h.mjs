// gen-glew-h.mjs — PRISM's <GL/glew.h>, written to src/env/glew-h.js.
//
// GLEW is a loader: glewInit fetches every entry point the driver has, and GLEW_<name> says whether
// the context offers an extension or a GL version. PRISM's GL needs no loading, so this header is
// GLEW's interface over plain calls: glewInit answers GLEW_OK, and glewIsSupported / glewGetExtension
// / each GLEW_<name> read glGetString(GL_EXTENSIONS) and glGetString(GL_VERSION) when asked. It is
// self-contained -- inline functions over GL alone -- so the reference build of the GL census links it
// against Mesa unchanged (tools/oracle.mjs's oracleGlut writes it beside PRISM's glut.h; the oracle
// has no libGLEW), and the two sides answer each question from their own GL.
//
// The names are every extension and version Mesa 22's <GL/glext.h> knows (in the oracle), so a program
// that tests one compiles whether or not PRISM offers it. GL_GLEXT_PROTOTYPES before <GL/gl.h>, as
// GLEW's own header makes the entry points visible: there they are its function pointers, here (and
// in Mesa's libGL) the functions themselves.
//
//   node tools/gen-glew-h.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sh } from './oracle.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const r = sh('cat /usr/include/GL/gl.h /usr/include/GL/glext.h');
if (r.code !== 0) throw new Error(`Mesa's headers: ${r.stderr}`);
const names = new Set(['GL_VERSION_1_1']);
for (const m of r.stdout.matchAll(/^#define (GL_[A-Za-z0-9]+_\w+) 1$/gm)) names.add(m[1]);
const sorted = [...names].sort();
const text = `#ifndef __glew_h__
#define __glew_h__
/* GENERATED by tools/gen-glew-h.mjs: GLEW's interface over PRISM's GL, which needs no loading. Do not edit. */
#ifndef GL_GLEXT_PROTOTYPES
#define GL_GLEXT_PROTOTYPES 1
#endif
#include <GL/gl.h>
#include <GL/glext.h>
#include <string.h>
#define GLEW_OK 0
#define GLEW_NO_ERROR 0
#define GLEW_ERROR_NO_GL_VERSION 1
#define GLEW_ERROR_GL_VERSION_10_ONLY 2
#define GLEW_ERROR_GLX_VERSION_11_ONLY 3
#define GLEW_VERSION 1
#define GLEW_VERSION_MAJOR 2
#define GLEW_VERSION_MINOR 3
#define GLEW_VERSION_MICRO 4
#ifndef GLEWAPI
#define GLEWAPI extern
#endif
static GLboolean glewExperimental = GL_FALSE;
static GLenum glewInit(void) { return GLEW_OK; }
/* One name: GL_VERSION_<major>_<minor> against glGetString(GL_VERSION), or an extension in GL_EXTENSIONS. */
static GLboolean glewGetExtension(const char *name) {
  const char *e;
  size_t n = strlen(name);
  if (!strncmp(name, "GL_VERSION_", 11)) {
    const char *v = (const char *)glGetString(GL_VERSION);
    int major = name[11] - '0', minor = name[13] - '0';
    if (!v) return GL_FALSE;
    return v[0] - '0' > major || (v[0] - '0' == major && v[2] - '0' >= minor);
  }
  for (e = (const char *)glGetString(GL_EXTENSIONS); e && *e;) {
    const char *sp = strchr(e, ' ');
    size_t len = sp ? (size_t)(sp - e) : strlen(e);
    if (len == n && !strncmp(e, name, n)) return GL_TRUE;
    if (!sp) break;
    e = sp + 1;
  }
  return GL_FALSE;
}
/* Space-separated names, every one supported. */
static GLboolean glewIsSupported(const char *names) {
  char one[128];
  while (*names) {
    size_t len = strcspn(names, " ");
    if (len && len < sizeof one) { memcpy(one, names, len); one[len] = 0; if (!glewGetExtension(one)) return GL_FALSE; }
    names += len;
    while (*names == ' ') names++;
  }
  return GL_TRUE;
}
static const GLubyte *glewGetErrorString(GLenum error) {
  return (const GLubyte *)(error == GLEW_OK ? "No error" : error == GLEW_ERROR_NO_GL_VERSION ? "Missing GL version" : "Unknown error");
}
static const GLubyte *glewGetString(GLenum name) { return (const GLubyte *)(name == GLEW_VERSION ? "2.2.0" : name == GLEW_VERSION_MAJOR ? "2" : name == GLEW_VERSION_MINOR ? "2" : name == GLEW_VERSION_MICRO ? "0" : 0); }
/* GLEW_<name>, for the ${sorted.length} names Mesa 22's <GL/glext.h> knows. */
${sorted.map((n) => `#define GLEW_${n.slice(3)} glewGetExtension("${n}")`).join('\n')}
#endif
`;
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
writeFileSync(join(ROOT, 'src/env/glew-h.js'), `// GENERATED by tools/gen-glew-h.mjs. Do not edit.
/** <GL/glew.h>: GLEW's interface over PRISM's GL (see tools/gen-glew-h.mjs). */
export const GLEW_H = \`${esc(text)}\`;
`);
console.log(`${sorted.length} names -> src/env/glew-h.js`);
