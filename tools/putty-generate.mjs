// putty-generate.mjs — the headers PuTTY's BUILD writes, written the same way.
//
//   node tools/putty-generate.mjs
//
// Two of PuTTY's headers do not exist in the source tree: cmake/licence.cmake makes `licence.h` out
// of the LICENCE file, and Buildscr makes `version.h` out of the release number. A real build
// generates them into its build directory, so this does too -- into corpus/putty-generated/, which
// is outside the source tree and gitignored with the rest of corpus/. The target puts that directory
// on its include path.
//
// The licence transformation is cmake/licence.cmake's, step for step, because LICENCE_TEXT is a
// macro that takes a paragraph separator: the text becomes one C string per paragraph with the
// caller's `parsep` between them. Getting that wrong would compile and produce a mangled licence,
// which is the kind of wrong that never gets noticed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SRC = join(ROOT, 'corpus/putty');
const OUT = join(ROOT, 'corpus/putty-generated');
mkdirSync(OUT, { recursive: true });

const licenceText = readFileSync(join(SRC, 'LICENCE'), 'utf8');
const cEscape = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

/* The copyright line is matched against the ORIGINAL text, before the paragraph folding below. */
const m = /PuTTY is copyright ([0-9]+-[0-9]+ [^\n]*[^\n.])\.?\n/.exec(licenceText);
if (!m) { console.error('LICENCE: no copyright line matching cmake/licence.cmake\'s regex'); process.exit(1); }
const copyright = cEscape(m[1]);

/* cmake/licence.cmake lines 17-25, in order: a paragraph break becomes \n, every other newline a space. */
let text = licenceText.replace(/\n$/, '').replace(/\r/g, '');
text = text.replace(/\n\n/g, '\r').replace(/\n/g, ' ').replace(/\r/g, '\n');
text = cEscape(text).replace(/\n/g, '" \\\n    parsep \\\n    "');

writeFileSync(join(OUT, 'licence.h'), `\
/*
 * licence.h - macro definitions for the PuTTY licence.
 *
 * Generated by tools/putty-generate.mjs from corpus/putty/LICENCE, following
 * corpus/putty/cmake/licence.cmake. Edit those, not this.
 */

#define LICENCE_TEXT(parsep) \\
    "${text}"

#define SHORT_COPYRIGHT_DETAILS "${copyright}"
`);

/* Buildscr:111-118. The release number is the tree's own LATEST.VER. */
const ver = readFileSync(join(SRC, 'LATEST.VER'), 'utf8').trim();
const commas = `${ver.split('.')[0]},${ver.split('.')[1] ?? 0},0,0`;
writeFileSync(join(OUT, 'version.h'), `\
/* Generated by tools/putty-generate.mjs, following corpus/putty/Buildscr:111-118. */
#define RELEASE ${ver}
#define TEXTVER "Release ${ver}"
#define SSHVER "PuTTY-Release-${ver}"
#define BINARY_VERSION ${commas}
`);

console.log(`corpus/putty-generated/: licence.h (copyright "${copyright}"), version.h (${ver})`);
